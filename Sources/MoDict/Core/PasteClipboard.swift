import AppKit
import os

/// Owns the pasteboard around a paste: what to give back afterwards, and when.
///
/// Restoration is guarded by a per-paste marker so it never clobbers something
/// the user copied in between, and runs on its own schedule so it outlives the
/// dictation that started it. A paste that arrives while a restore is pending
/// takes it over: the pasteboard then holds our own text, so the snapshot taken
/// before the first paste remains the one to give back.
@MainActor
final class PasteClipboard {
    typealias Scheduler = @MainActor (_ delay: Duration, _ action: @escaping @MainActor @Sendable () -> Void) -> Void

    /// Identifies one write; an outdated ticket can no longer restore anything.
    struct Ticket: Equatable {
        fileprivate let generation: Int
    }

    private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private struct Pending {
        let original: Snapshot
        let text: String
        let sessionID: String
        let generation: Int
    }

    /// Slow apps read the pasteboard well after receiving ⌘V.
    static let restoreDelay: Duration = .milliseconds(500)
    private static let slowSnapshot: Duration = .milliseconds(50)
    private static let logger = Logger(subsystem: "com.modict.app", category: "clipboard")

    // Session marker + nspasteboard.org transient types. Clipboard managers
    // (Paste, Maccy, Raycast) skip the transient-tagged entry; the session UUID
    // lets us prove the pasteboard is still ours before restoring.
    private let sessionType   = NSPasteboard.PasteboardType("com.modict.PasteSession")
    private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let autoGenType   = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private let sourceType    = NSPasteboard.PasteboardType("org.nspasteboard.source")

    private let pasteboard: NSPasteboard
    private let schedule: Scheduler
    private let writeString: @MainActor (NSPasteboard, String) -> Bool
    private var generation = 0
    private var pending: Pending?

    init(pasteboard: NSPasteboard,
         schedule: @escaping Scheduler = PasteClipboard.sleepingScheduler,
         writeString: @escaping @MainActor (NSPasteboard, String) -> Bool = { $0.setString($1, forType: .string) }) {
        self.pasteboard = pasteboard
        self.schedule = schedule
        self.writeString = writeString
    }

    /// Unstructured, so cancelling the dictation that scheduled it changes nothing.
    nonisolated static let sleepingScheduler: Scheduler = { delay, action in
        Task { @MainActor in
            try? await Task.sleep(for: delay)
            action()
        }
    }

    /// Puts `text` on the pasteboard and supersedes any pending restore. Returns
    /// nil when the write failed, in which case the original is already back.
    func write(_ text: String, restoring: Bool) -> Ticket? {
        generation += 1
        let original = restoring ? (heldOriginal() ?? takeSnapshot()) : nil
        pending = nil

        let sessionID = UUID().uuidString
        guard writeToPasteboard(text, sessionID: sessionID, restoring: restoring) else {
            if let original { put(original) }
            return nil
        }
        pending = original.map { Pending(original: $0, text: text, sessionID: sessionID, generation: generation) }
        return Ticket(generation: generation)
    }

    /// The paste went out: give the target app time to read, then restore.
    func schedulePasteRestore(_ ticket: Ticket) {
        guard pending?.generation == ticket.generation else { return }
        schedule(Self.restoreDelay) { self.restoreNow(ticket) }
    }

    /// Restores unless a newer write took over or the user copied something.
    /// Also the path for a paste that never went out.
    func restoreNow(_ ticket: Ticket) {
        guard let pending, pending.generation == ticket.generation else { return }
        self.pending = nil
        if isOnPasteboard(pending) { put(pending.original) }
    }

    /// The app is quitting: a timer would die with the process and leave the dictated
    /// text in place of the user's clipboard for good.
    func flushPendingRestore() {
        guard let pending else { return }
        self.pending = nil
        if isOnPasteboard(pending) { put(pending.original) }
    }

    // MARK: - Pasteboard

    private func heldOriginal() -> Snapshot? {
        guard let pending, isOnPasteboard(pending) else { return nil }
        return pending.original
    }

    /// Matches both the text and the UUID, not just `changeCount`, so a copy made
    /// during the paste window is left untouched.
    private func isOnPasteboard(_ pending: Pending) -> Bool {
        pasteboard.string(forType: .string) == pending.text
            && pasteboard.string(forType: sessionType) == pending.sessionID
    }

    /// Every item as its (type, Data) pairs so arbitrary flavors survive the
    /// round-trip. `data(forType:)` can make the owning app materialize promised
    /// data, on the main actor, so a slow snapshot is worth knowing about.
    private func takeSnapshot() -> Snapshot {
        let clock = ContinuousClock()
        let start = clock.now
        let snapshot = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { (type, $0) }
            }
        }
        let elapsed = start.duration(to: clock.now)
        if elapsed > Self.slowSnapshot {
            let milliseconds = Int(elapsed / .milliseconds(1))
            Self.logger.warning("Clipboard snapshot took \(milliseconds, privacy: .public) ms")
        }
        return snapshot
    }

    private func writeToPasteboard(_ text: String, sessionID: String, restoring: Bool) -> Bool {
        pasteboard.clearContents()
        guard writeString(pasteboard, text) else { return false }
        if let bundleID = Bundle.main.bundleIdentifier {
            pasteboard.setString(bundleID, forType: sourceType)
        }
        if restoring {
            // Transient markers keep clipboard managers from recording the paste;
            // the session UUID is what we check before restoring.
            pasteboard.setData(Data(), forType: transientType)
            pasteboard.setData(Data(), forType: autoGenType)
            pasteboard.setString(sessionID, forType: sessionType)
        }
        return true
    }

    private func put(_ snapshot: Snapshot) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        pasteboard.writeObjects(snapshot.map { pairs in
            let item = NSPasteboardItem()
            for (type, data) in pairs {
                item.setData(data, forType: type)
            }
            return item
        })
    }
}
